#!/usr/bin/env node
// The site's files that come straight from the data March publishes with the release:
//   public/comp/<category>.json   each component's props table, notes and accessibility (data/comp/)
//   src/home-stats.gen.ts         the home page's numbers (data/stats.json) with the site's budgets (march.config.js)
//   src/text-costs.gen.ts         each text animation's cost, the text motion page's badges (data/text-costs.json)
// A release that does not publish them yet leaves the committed files as they are.
//   node tools/march-data.mjs            write them
//   node tools/march-data.mjs --check    exit 1 when one is out of date
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { SITE, dataFile, dataFiles, marchVersion } from "./march.mjs";

export async function generate() {
  const all = await dataFiles();
  const files = {};
  for (const rel of all.filter((f) => f.startsWith("comp/"))) files[`public/${rel}`] = readFileSync(await dataFile(rel), "utf8");
  if (all.includes("stats.json")) {
    const stats = JSON.parse(readFileSync(await dataFile("stats.json"), "utf8"));
    const cfg = (await import(pathToFileURL(join(SITE, "march.config.js")).href)).default;
    const b = cfg.budget ?? {};
    stats.budget = { entry: b.entry ?? 0, boot: b.bootLimit ?? 0, route: b.route ?? 0, partFloor: cfg.chunks?.minSize ?? 0 };
    files["src/home-stats.gen.ts"] = "// GENERATED by tools/march-data.mjs — do not edit. The home page's numbers: March's (cdn.marchjs.com/<version>/data/stats.json)\n" +
      "// and the site's budgets (march.config.js). Measured sizes come from march-report.json at run time.\n" +
      `export const HOME_STATS = ${JSON.stringify(stats, null, 2)} as const;\n` +
      "export type HomeStats = typeof HOME_STATS;\n";
  }
  if (all.includes("text-costs.json")) {
    const t = JSON.parse(readFileSync(await dataFile("text-costs.json"), "utf8"));
    files["src/text-costs.gen.ts"] = "// GENERATED by tools/march-data.mjs — do not edit. March's data/text-costs.json (cdn.marchjs.com/<version>/data/):\n" +
      `// gzip bytes one text animation import adds over the motion engine (${t.engine} B): shared text core + the animation.\n` +
      "export const TEXT_COSTS: Record<string, number> = {\n" + Object.entries(t.costs).map(([k, v]) => `  ${k}: ${v},\n`).join("") + "};\n";
  }
  return files;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const files = await generate();
  let stale = false;
  for (const [rel, text] of Object.entries(files)) {
    const p = join(SITE, rel);
    if ((existsSync(p) ? readFileSync(p, "utf8") : "") === text) continue;
    stale = true;
    if (check) console.error(`✖ ${rel} is out of date: node tools/march-data.mjs`);
    else { mkdirSync(join(p, ".."), { recursive: true }); writeFileSync(p, text); }
  }
  const n = Object.keys(files).length;
  console.log(`march data (March ${await marchVersion()}): ${n ? `${n} files` : "comp/, stats.json and text-costs.json not published by this release: committed files kept"}`);
  if (check && stale) process.exit(1);
}
