#!/usr/bin/env node
// The texts of MarchIDE's ide.json files (public/components/**/ide.json › description), written into
// a module as t`…` calls: the build collects them with the showcase's other texts (dist/i18n-keys.json, `march i18n`
// lists the missing translations), and MarchIDE shows a description through t(text), so a translation takes its place.
// ide.json is data the page fetches, not code the compiler reads: this module is how its texts reach the extraction
// (a .tsx file: the March compiler, which collects the t`…` texts, reads .tsx / .jsx).
// A text with { } is refused (t() would read them as placeholders), as are ` and ${ (they would end the literal).
// It also writes the list of the pages that have an ide.json (ide-list.gen.ts): a component page whose slug has
// public/components/<slug>/ide.json is MarchIDE (playground/ide-pages.ts), with no line to add by hand.
//   node tools/gen-ide-texts.js            write src/playground/ide-texts.gen.tsx and ide-list.gen.ts
//   node tools/gen-ide-texts.js --check    exit 1 when it is out of date
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { join, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
export const IN = "public/components";
export const OUT = "src/playground/ide-texts.gen.tsx";
export const LIST = "src/playground/ide-list.gen.ts";

/** The list module: the folders under public/components that hold an ide.json ("button", "icon-button"…), sorted. */
export function generateList(root = ROOT) {
  const dir = join(root, IN);
  const names = existsSync(dir) ? readdirSync(dir).sort().filter((n) => existsSync(join(dir, n, "ide.json"))) : [];
  return `// GENERATED by tools/gen-ide-texts.js from ${IN}/<name>/ide.json — do not edit.
/** The component pages that are MarchIDE: public/components/<name>/ide.json exists (playground/ide-pages.ts). */
export const IDE_COMPONENTS: readonly string[] = [${names.map((n) => JSON.stringify(n)).join(", ")}];
`;
}

const walk = (d) => (existsSync(d) ? readdirSync(d).sort().flatMap((n) => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : n === "ide.json" ? [p] : []; }) : []);

/** The module's text: every ide.json's description, in path order (each once). */
export function generate(root = ROOT) {
  const seen = new Set(), lines = [];
  for (const file of walk(join(root, IN))) {
    const where = relative(root, file).split("\\").join("/");
    const text = JSON.parse(readFileSync(file, "utf8")).description;
    if (text === undefined) continue;
    if (typeof text !== "string") throw new Error(`${where}: "description" must be a string`);
    if (/[{}`]|\$\{/.test(text)) throw new Error(`${where}: "description" may not hold { } or \` (t() reads braces as placeholders)`);
    if (!text.trim() || seen.has(text)) continue;
    seen.add(text);
    lines.push(`  // ${where}`, `  t\`${text.replace(/\\/g, "\\\\")}\`,`);
  }
  return `// GENERATED by tools/gen-ide-texts.js from ${IN}/**/ide.json — do not edit.
// The ide.json descriptions as t\`…\`: the build collects them with the showcase's texts (i18n-keys.json); MarchIDE
// shows a description through t(text), so its translation, when there is one, is what appears.
import { t } from "march";

/** Never called: it is here so the compiler sees the texts. */
export const IDE_TEXTS = (): string[] => [
${lines.join("\n")}
];
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [rel, next] of [[OUT, generate()], [LIST, generateList()]]) {
    const out = join(ROOT, rel), now = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (process.argv.includes("--check")) {
      if (now !== next) { console.error(`✖ ${rel} is out of date: node tools/gen-ide-texts.js`); process.exit(1); }
    } else if (now !== next) writeFileSync(out, next);
  }
}
