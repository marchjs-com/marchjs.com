#!/usr/bin/env node
// The texts of MarchIDE's ide.json files (› description), written into a module as t`…` calls: the build collects them
// with the showcase's other texts (dist/i18n-keys.json, `march i18n` lists the missing translations), and MarchIDE
// shows a description through t(text), so a translation takes its place.
// ide.json is data the page fetches, not code the compiler reads: this module is how its texts reach the extraction
// (a .tsx file: the March compiler, which collects the t`…` texts, reads .tsx / .jsx).
// A text with { } is refused (t() would read them as placeholders), as are ` and ${ (they would end the literal).
// It also writes the list of the pages that have an ide.json (ide-list.gen.ts): a component page whose slug has
// components/<slug>/ide.json in the examples is MarchIDE (playground/ide-pages.ts), with no line to add by hand.
// The ide.json files live in github.com/marchjs-com/examples: its root ide.json holds them all. This reads it at the
// sha the site is pinned to (src/playground/examples.ts), from jsDelivr, kept in node_modules/.cache/march-examples/
// (a sha's files never change); MARCH_EXAMPLES_DIR=<a local checkout> reads that checkout's ide.json instead.
//   node tools/gen-ide-texts.js            write src/playground/ide-texts.gen.tsx and ide-list.gen.ts
//   node tools/gen-ide-texts.js --check    exit 1 when it is out of date
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
export const PIN = "src/playground/examples.ts";
export const OUT = "src/playground/ide-texts.gen.tsx";
export const LIST = "src/playground/ide-list.gen.ts";

/** The examples' base URL the site is pinned to (…/examples@<sha>/) and its sha. */
export function pinned(root = ROOT) {
  const m = /EXAMPLES = "(https:\/\/cdn\.jsdelivr\.net\/gh\/marchjs-com\/examples@([0-9a-f]{40})\/)"/.exec(readFileSync(join(root, PIN), "utf8"));
  if (!m) throw new Error(`${PIN}: EXAMPLES must be the examples repository pinned to a 40-character sha`);
  return { base: m[1], sha: m[2] };
}

/** Every page's ide.json, keyed by "components/<page>": the examples' root ide.json at the pinned sha. */
export async function readBundle(root = ROOT) {
  const local = process.env.MARCH_EXAMPLES_DIR;
  if (local) return JSON.parse(readFileSync(join(local, "ide.json"), "utf8"));
  const { base, sha } = pinned(root);
  const dir = join(root, "node_modules", ".cache", "march-examples", sha), file = join(dir, "ide.json");
  if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8"));
  const res = await fetch(`${base}ide.json`);
  if (!res.ok) throw new Error(`${base}ide.json: ${res.status} (MARCH_EXAMPLES_DIR=<checkout> reads a local copy)`);
  const text = await res.text();
  const bundle = JSON.parse(text);
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, text);
  return bundle;
}

const names = (bundle) => Object.keys(bundle).filter((k) => k.startsWith("components/")).map((k) => k.slice("components/".length)).sort();

/** The list module: the pages with an ide.json ("button", "icon-button"…), sorted. */
export function generateList(bundle) {
  return `// GENERATED by tools/gen-ide-texts.js from the examples' ide.json (components/<name>) — do not edit.
/** The component pages that are MarchIDE: components/<name>/ide.json exists in the examples (playground/ide-pages.ts). */
export const IDE_COMPONENTS: readonly string[] = [${names(bundle).map((n) => JSON.stringify(n)).join(", ")}];
`;
}

/** The module's text: every ide.json's description, in path order (each once). */
export function generate(bundle) {
  const seen = new Set(), lines = [];
  for (const name of names(bundle)) {
    const where = `components/${name}/ide.json`;
    const text = bundle[`components/${name}`].description;
    if (text === undefined) continue;
    if (typeof text !== "string") throw new Error(`${where}: "description" must be a string`);
    if (/[{}`]|\$\{/.test(text)) throw new Error(`${where}: "description" may not hold { } or \` (t() reads braces as placeholders)`);
    if (!text.trim() || seen.has(text)) continue;
    seen.add(text);
    lines.push(`  // ${where}`, `  t\`${text.replace(/\\/g, "\\\\")}\`,`);
  }
  return `// GENERATED by tools/gen-ide-texts.js from the examples' ide.json files — do not edit.
// The ide.json descriptions as t\`…\`: the build collects them with the showcase's texts (i18n-keys.json); MarchIDE
// shows a description through t(text), so its translation, when there is one, is what appears.
import { t } from "march";

/** Never called: it is here so the compiler sees the texts. */
export const IDE_TEXTS = (): string[] => [
${lines.join("\n")}
];
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const bundle = await readBundle();
  for (const [rel, next] of [[OUT, generate(bundle)], [LIST, generateList(bundle)]]) {
    const out = join(ROOT, rel), now = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (process.argv.includes("--check")) {
      if (now !== next) { console.error(`✖ ${rel} is out of date: node tools/gen-ide-texts.js`); process.exit(1); }
    } else if (now !== next) writeFileSync(out, next);
  }
}
