#!/usr/bin/env node
// The start-up form of src/topics.ts: every topic page's path, title and menu parent, nothing else
// (src/topic-titles.gen.ts). Start-up needs them for the routes, the breadcrumb and the document title; the
// descriptions, March names and groups (most of topics.ts) stay in topics.ts, which only lazy code loads (the side
// menu's manifest, the section pages, MarchIDE).
//   node tools/gen-topic-titles.mjs            write src/topic-titles.gen.ts
//   node tools/gen-topic-titles.mjs --check    exit 1 when it is out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const OUT = join(ROOT, "src/topic-titles.gen.ts");
// topics.ts is data with erasable types only: Node reads it directly
const { HUBS, TOPIC_PAGES } = await import(pathToFileURL(join(ROOT, "src/topics.ts")).href);

const rows = TOPIC_PAGES.map((p) => (p.parent === p.path.slice(0, p.path.lastIndexOf("/")) ? [p.path, p.title] : [p.path, p.title, p.parent]));
const text = `// GENERATED by tools/gen-topic-titles.mjs from src/topics.ts — do not edit.
// Start-up's part of topics.ts: the sections with one page per topic, and each topic page's path, title and (when it is
// not the section) menu parent. Descriptions and names: topics.ts (lazy code only).

/** The sections with one page per topic (/editors, /forms…). */
export const HUB_BASES: readonly string[] = ${JSON.stringify(Object.keys(HUBS))};
/** [path, title, parent?] of every topic page; without a parent, the page is listed under the path's parent. */
export const TOPIC_ROWS: readonly (readonly [string, string, string?])[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) { console.error("✖ src/topic-titles.gen.ts is out of date: node tools/gen-topic-titles.mjs"); process.exit(1); }
} else if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
  writeFileSync(OUT, text);
  console.log(`wrote src/topic-titles.gen.ts (${rows.length} topic pages)`);
}
