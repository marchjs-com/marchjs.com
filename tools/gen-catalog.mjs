#!/usr/bin/env node
// The component catalog of the site (src/catalog/): a card for every March component, its live demo and its Options
// panel. March publishes the components (data/components.json: folder, category, meta, docs.md) and the API index
// (data/api/index.en.json); the demos and the option specs are the site's own (src/catalog/<category>/<name>/demo.tsx,
// playground.ts), and so is the page each card is drawn on (showcase.json; pages.json: a component's own page).
//   src/catalog/registry.gen.ts       every component: meta (name, summary, composedOf), Code-tab snippet, demo / spec loaders
//   src/catalog/cards.gen.ts          what a card draws (name, summary, parts, its page, its API page) and the loaders
//   src/catalog/cards-code.gen.ts     the Code-tab snippets (one lazy module, loaded on the first Code tab)
//   src/catalog/cards-roots.gen.ts    component name → the class of its root element (the exploded view)
//   src/catalog/cards-parts.gen.ts    component name → a loader of the component (a composite's parts on the stage)
//   src/catalog/<page>[-n].demos.gen.ts, <page>.kit.gen.ts   the demos of one page, a few per lazy module
//   node tools/gen-catalog.mjs          write
//   node tools/gen-catalog.mjs --check  exit 1 when a file is out of date, or a March component has no demo / Options panel
import { readFileSync, writeFileSync, existsSync, readdirSync, unlinkSync, mkdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { SITE, MARCH, dataFile, marchVersion } from "./march.mjs";

const DIR = join(SITE, "src", "catalog");
const HEAD = "// GENERATED by tools/gen-catalog.mjs from March's data/components.json and src/catalog/ — do not edit.\n";
const firstCode = (md) => md.match(/```\w*\n([\s\S]*?)```/)?.[1].trim() ?? "";
const nameOf = (c) => c.meta?.name ?? c.name;

export async function generate() {
  const data = JSON.parse(readFileSync(await dataFile("components.json"), "utf8"));
  const list = [...data.components].sort((a, b) => a.name.localeCompare(b.name, "en"));
  const showcase = JSON.parse(readFileSync(join(DIR, "showcase.json"), "utf8"));
  const sitePages = JSON.parse(readFileSync(join(DIR, "pages.json"), "utf8"));
  const pageOf = (c) => showcase[c.folder]?.page;
  const groupName = (c) => showcase[c.folder]?.group;
  const problems = [];
  for (const c of list) for (const f of ["demo.tsx", "playground.ts"]) if (!existsSync(join(DIR, c.folder, f))) problems.push(`src/catalog/${c.folder}/${f} is missing: every March component has a card with a live demo and an Options panel`);
  for (const c of list) if (!pageOf(c)) problems.push(`src/catalog/showcase.json: "${c.folder}" has no page`);
  // every card has an Options panel (at least one option), and every option reaches the demo: a key the demo never
  // reads is a control that changes nothing (props.values.key, an alias of props.values, or a destructured key)
  for (const c of list) {
    const specFile = join(DIR, c.folder, "playground.ts"), demoFile = join(DIR, c.folder, "demo.tsx");
    if (!existsSync(specFile) || !existsSync(demoFile)) continue;
    const spec = readFileSync(specFile, "utf8"), demo = readFileSync(demoFile, "utf8");
    if (!/\bkey:\s*"/.test(spec)) problems.push(`src/catalog/${c.folder}/playground.ts declares no option: the card's Options panel would be empty`);
    const names = ["values", ...[...demo.matchAll(/(?:const|let|,)\s*(\w+)\s*=\s*(?:\{\s*\.\.\.)?props\.values(?![.\w])/g)].map((m) => m[1])].join("|");
    for (const [, key] of spec.matchAll(/\bkey:\s*"([^"]+)"/g)) {
      const read = new RegExp(`\\b(${names})\\.${key}\\b|\\b(${names})\\[["']${key}["']\\]|[{,]\\s*${key}\\s*[,}=:][^\\n]*=\\s*props\\.values`).test(demo);
      if (!read) problems.push(`src/catalog/${c.folder}: the option "${key}" is never read by demo.tsx (it changes nothing)`);
    }
  }
  const known = new Set(list.map((c) => c.folder));
  for (const cat of readdirSync(DIR, { withFileTypes: true }).filter((d) => d.isDirectory())) {
    for (const n of readdirSync(join(DIR, cat.name), { withFileTypes: true }).filter((d) => d.isDirectory())) {
      if (!known.has(`${cat.name}/${n.name}`)) problems.push(`src/catalog/${cat.name}/${n.name}: no such component in March ${await marchVersion()}`);
    }
  }
  // a component's own package entry, march/components/<category>/<name> (also one CDN module each)
  const subpath = (c) => `march/components/${c.folder}`;
  // the API index: subpaths with their names and kinds (the same order as March's package exports)
  const api = JSON.parse(readFileSync(await dataFile("api/index.en.json"), "utf8")).subpaths.map((s) => ({ subpath: s.subpath, slug: s.slug, items: s.items.map((i) => [i[0], i[1]]) }));
  const exportName = (c) => (api.some((x) => x.items.some((it) => it[0] === nameOf(c))) ? nameOf(c) : nameOf(c)[0].toLowerCase() + nameOf(c).slice(1));
  const files = {};

  // Demos shown on the same page load together, up to GROUP per lazy module (<page>[-n].demos.gen.ts): one small chunk
  // per demo would fall under the 10 KB chunk floor and fold into the registry's parent group, which every page with a
  // component card loads; one module for a page with many cards would pass the lazy part budget. Members are in
  // folder-name order, so related folders (chat-…, story-…) usually share a module. A page with a single component card
  // keeps its direct import. A group in showcase.json names a family that loads together; the page's building blocks
  // share one kit (<page>.kit.gen.ts).
  const GROUP = 3;
  const partNames = new Set(list.flatMap((c) => c.meta?.composedOf ?? []));
  const pages = new Map();
  // a large component (barrel: false) keeps its own demo module: its code alone is over the chunk floor, and grouping
  // it would make every card of the page download it; a component with its own entry is drawn by its page
  for (const c of list) if (pageOf(c) && c.meta?.barrel !== false && !c.meta?.entry) pages.set(pageOf(c), [...(pages.get(pageOf(c)) ?? []), c]);
  const groupOf = new Map();
  for (const [page, all] of pages) {
    if (all.length < 2) continue;
    const base = page.replace(/^\//, "").replace(/[^\w-]+/g, "-") || "home";
    const named = new Map(), rest = [];
    for (const c of all) if (groupName(c)) named.set(groupName(c), [...(named.get(groupName(c)) ?? []), c]); else rest.push(c);
    const parts = [...named].map(([g, members]) => ({ name: `${base}-${g}`, members }));
    const slices = Math.ceil(rest.length / GROUP);
    for (let s = 0; s < slices; s++) parts.push({ name: `${base}${slices > 1 || parts.length ? `-${s + 1}` : ""}`, members: rest.slice(Math.floor((s * rest.length) / slices), Math.floor(((s + 1) * rest.length) / slices)) });
    // landing blocks are many and large: only the ones other blocks are built from (composedOf) go in the kit, the rest
    // stay in their family module; the category's demo data (<category>/demo-kit.tsx) rides in the kit too
    const usedByOthers = (c) => all.some((o) => o !== c && (o.meta?.composedOf ?? []).includes(nameOf(c)));
    const blocks = parts.length > 1 ? all.filter((c) => c.category && c.category !== "composite" && (c.category !== "landing" || usedByOthers(c))) : [];
    const demoKits = [...new Set(blocks.map((c) => c.category))].filter((k) => existsSync(join(DIR, k, "demo-kit.tsx")));
    const kit = blocks.length > 1 ? `${base}.kit.gen.ts` : null;
    const gen = (what) => `// GENERATED by tools/gen-catalog.mjs: ${what} — do not edit.\n`;
    if (kit) {
      const bySub = new Map();
      for (const c of blocks) bySub.set(subpath(c), [...(bySub.get(subpath(c)) ?? []), exportName(c)]);
      files[kit] = gen(`the building blocks shown on ${page}`) + [...bySub].map(([s, ns]) => `import { ${ns.join(", ")} } from "${s}";\n`).join("") +
        `export { ${[...bySub.values()].flat().join(", ")} };\n` + demoKits.map((k) => `export * from "./${k}/demo-kit.tsx";\n`).join("");
    }
    for (const { name, members } of parts) {
      // *.demos.gen.ts: the site config lets these stay small lazy files (chunks.allow), never joining the registry
      const file = `${name}.demos.gen.ts`;
      members.forEach((c, j) => groupOf.set(c.folder, { file, j }));
      files[file] = gen(`the component folders shown on ${page}`) + (kit ? `export * from "./${kit}";\n` : "") +
        members.map((c, j) => `import * as d${j} from "./${c.folder}/demo.tsx";\nimport * as p${j} from "./${c.folder}/playground.ts";\n`).join("") +
        `export { ${members.map((_, j) => `d${j}, p${j}`).join(", ")} };\n`;
    }
  }
  // a component with its own entry is shown statically on its page: no lazy demo loader (a lazy demo would be a part
  // carrying the whole feature), the page imports demo.tsx and playground.ts itself (its option spec is plain data, so
  // MarchIDE still loads playground.ts lazily)
  const loader = (c, kind, file) => { if (c.meta?.entry && kind === "d") return `() => ownPage("${nameOf(c)}")`; if (c.meta?.entry) return `() => import("./${c.folder}/${file}")`; const g = groupOf.get(c.folder); return g ? `() => import("./${g.file}").then((m) => m.${kind}${g.j})` : `() => import("./${c.folder}/${file}")`; };
  const metaOf = (c) => ({ name: nameOf(c), summary: c.meta?.summary ?? "", composedOf: c.meta?.composedOf ?? [] });
  files["registry.gen.ts"] = HEAD + `import type { PlaygroundSpec } from "./spec.ts";\n` +
    `\n/** A component as March publishes it (data/components.json): the fields the site reads. */\nexport interface CatalogMeta { name: string; summary: string; composedOf: readonly string[] }\n` +
    `export interface RegistryEntry { folder: string; meta: CatalogMeta; /** First code block of docs.md (the Code tab). */ code: string; demo: () => Promise<{ default: (p: { values: never }) => unknown; code?: string }>; playground: () => Promise<{ default: PlaygroundSpec<never> }> }\n` +
    (list.some((c) => c.meta?.entry) ? `const ownPage = (name: string): Promise<never> => Promise.reject(new Error(\`\${name} has its own entry: its page imports the demo\`));\n` : "") +
    `/** Every component: meta, Code-tab snippet and lazy demo / Options loaders. */\nexport const registry: readonly RegistryEntry[] = [\n` +
    list.map((c) => `  { folder: "${c.folder}", meta: ${JSON.stringify(metaOf(c))}, code: ${JSON.stringify(firstCode(c.docs))}, demo: ${loader(c, "d", "demo.tsx")}, playground: ${loader(c, "p", "playground.ts")} },\n`).join("") + `];\n`;
  // the card's catalog: only what a card draws (name, summary, parts, the page of each part, the Code tab) and the lazy
  // loaders. The Code-tab snippets are their own lazy module (cards-code.gen.ts), loaded on the first click on a Code tab.
  // A grouped demo module is one loader shared by its cards (L(group, index)); a folder of its own keeps its two imports.
  const groups = [...new Set([...groupOf.values()].map((g) => g.file))];
  // w: the component's own page (pages.json), else the page it is shown on; a: its API reference page (/api/<a>/<name>)
  const ownPageOf = (c) => sitePages[c.folder] ?? pageOf(c);
  const apiOf = (c) => api.find((x) => x.items.some((it) => it[0] === nameOf(c) && it[1] === "component"))?.slug ?? api.find((x) => x.items.some((it) => it[0] === nameOf(c) || it[0] === nameOf(c)[0].toLowerCase() + nameOf(c).slice(1)))?.slug;
  const pick = (c) => ({ f: c.folder, n: nameOf(c), s: c.meta?.summary ?? "", ...(c.meta?.composedOf?.length ? { p: c.meta.composedOf } : {}), ...(ownPageOf(c) ? { w: ownPageOf(c) } : {}), ...(apiOf(c) ? { a: `${apiOf(c)}/${exportName(c)}` } : {}) });
  const load = (c) => {
    if (c.meta?.entry) return `demo: own, playground: () => import("./${c.folder}/playground.ts")`;
    const g = groupOf.get(c.folder);
    return g ? `...L(${groups.indexOf(g.file)}, ${g.j})` : `demo: () => import("./${c.folder}/demo.tsx"), playground: () => import("./${c.folder}/playground.ts")`;
  };
  files["cards.gen.ts"] = HEAD + `import type { PlaygroundSpec } from "./spec.ts";\n` +
    `\n/** f: folder, n: name, s: summary, p: composedOf, w: showcase page, a: API reference page under /api (the Code tab: cardCode(folder)). */\n` +
    `export interface CardEntry { f: string; n: string; s: string; p?: readonly string[]; w?: string; a?: string; demo: () => Promise<{ default: (p: { values: never }) => unknown; code?: string }>; playground: () => Promise<{ default: PlaygroundSpec<never> }> }\n` +
    `type Mod = Record<string, { default: never }>;\nconst G: (() => Promise<Mod>)[] = [${groups.map((f) => `() => import("./${f}") as Promise<never>`).join(", ")}];\n` +
    `const L = (i: number, j: number) => ({ demo: () => G[i]!().then((m) => m[\`d\${j}\`]!), playground: () => G[i]!().then((m) => m[\`p\${j}\`]!) });\n` +
    (list.some((c) => c.meta?.entry) ? `const own = (): Promise<never> => Promise.reject(new Error("this component has its own entry: its page imports the demo"));\n` : "") +
    `/** Every component as a card needs it (registry.gen.ts has more). */\nexport const cards: readonly CardEntry[] = [\n` +
    list.map((c) => `  { ${JSON.stringify(pick(c)).slice(1, -1)}, ${load(c)} },\n`).join("") + `];\n` +
    `/** The Code-tab snippet of a folder (one lazy module for every card). */\nexport const cardCode = (folder: string): Promise<string> => import("./cards-code.gen.ts").then((m) => m.code[folder] ?? "");\n`;
  // the class of each component's root element (March publishes it as `root`; before 0.3.6: meta.root, else the first
  // class the component's stylesheet styles in the installed sources): how a card finds the parts of a composite
  const rootClass = (c) => {
    if (c.root !== undefined) return c.root;
    if (c.meta?.root) return c.meta.root;
    const dir = join(MARCH, "src", "components", c.folder);
    const css = existsSync(dir) ? readdirSync(dir).find((f) => f.endsWith(".css")) : null;
    return css ? /^\.(m-[a-z0-9-]+)/m.exec(readFileSync(join(dir, css), "utf8").replace(/\/\*[\s\S]*?\*\//g, ""))?.[1] ?? null : null;
  };
  files["cards-roots.gen.ts"] = HEAD + "/** Component name → the class of its root element. */\nexport const roots: Record<string, string> = {\n" +
    list.filter((c) => rootClass(c)).map((c) => `  ${JSON.stringify(nameOf(c))}: ${JSON.stringify(rootClass(c))},\n`).join("") + "};\n";
  // the components other components are built from (every name in a composedOf), each behind a loader: a card gives
  // them props through m:parts when a part of a composite is chosen on the stage: each loads the component's own entry.
  const partList = list.filter((c) => partNames.has(nameOf(c)) && !c.meta?.entry);
  const partLoader = (c) => `() => import("${subpath(c)}").then((m) => m.${exportName(c)})`;
  files["cards-parts.gen.ts"] = HEAD + "/** Component name → a loader of the component itself (the key of an m:parts map). */\n" +
    "export const parts: Record<string, () => Promise<unknown>> = {\n" +
    partList.map((c) => `  ${nameOf(c)}: ${partLoader(c)},\n`).join("") + "};\n";
  files["cards-code.gen.ts"] = HEAD + `export const code: Record<string, string> = {\n` +
    list.map((c) => `  ${JSON.stringify(c.folder)}: ${JSON.stringify(firstCode(c.docs))},\n`).join("") + `};\n`;
  return { files, problems };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const { files, problems } = await generate();
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const p = join(DIR, rel);
    if ((existsSync(p) ? readFileSync(p, "utf8") : null) === text) continue;
    if (check) { console.error(`✖ src/catalog/${rel} is out of date: node tools/gen-catalog.mjs`); stale++; }
    else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); }
  }
  // generated modules of an earlier slicing (fewer cards, a page renamed) go away
  const old = readdirSync(DIR).filter((f) => f.endsWith(".gen.ts") && !files[f]);
  for (const f of old) {
    if (check) { console.error(`✖ src/catalog/${f} is stale: node tools/gen-catalog.mjs`); stale++; }
    else unlinkSync(join(DIR, f));
  }
  for (const p of problems) console.error(`✖ ${p}`);
  console.log(`catalog (March ${await marchVersion()}): ${Object.keys(files).length} files${check && !stale ? ", up to date" : ""}`);
  if (stale || problems.length) process.exit(1);
}
